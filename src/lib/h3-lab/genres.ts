export function genreById(id: string): GenreModule | undefined {
  return GENRES.find((x) => x.id === id);
}

export function genreName(id: string): string {
  return genreById(id)?.name ?? id;
}

/** Weight of a dimension in a genre (0.5 when the module is silent). */
export function weightOf(genre: string, d: Dimension): number {
  const w = genreById(genre)?.weights[d];
  return typeof w === "number" ? w : 0.5;
}

/**
 * Pick the genre for free text ("a fight in a parking garage") — keyword match,
 * no AI, so the compiler works offline. Falls back to movie-scene.
 */
export function guessGenre(text: string): string {
  const t = text.toLowerCase();
  const rules: [RegExp, string][] = [
    [/\b(fight|punch|kick|brawl)\b/, "fight-scene"],
    [/\b(kung ?fu|karate|martial)\b/, "martial-arts"],
    [/\b(car chase|chase|pursuit)\b/, /police|cop/.test(t) ? "police-pursuit" : "car-chase"],
    [/\b(explosion|explodes|blast)\b/, "explosion"],
    [/\b(battle|army|armies)\b/, "battle"],
    [/\b(sitcom|laugh track)\b/, "sitcom"],
    [/\b(sketch|comedy|funny)\b/, "comedy-sketch"],
    [/\b(horror|ghost|haunted|scary)\b/, "horror"],
    [/\b(thriller)\b/, "psychological-thriller"],
    [/\b(romance|romantic|kiss|date)\b/, "romantic-drama"],
    [/\b(micro ?drama|episode)\b/, "micro-drama"],
    [/\b(trailer)\b/, /game/.test(t) ? "game-trailer" : "movie-trailer"],
    [/\b(teaser)\b/, "cinematic-teaser"],
    [/\b(music video|singer|rapper|performance)\b/, "music-video"],
    [/\b(product|bottle|sneaker|watch|ad)\b/, "product-ad"],
    [/\b(fashion|runway|model walk)\b/, "fashion"],
    [/\b(tiktok|reel|shorts|viral)\b/, "viral-short"],
    [/\b(dragon|creature|monster)\b/, "creature-encounter"],
    [/\b(superhero|powers)\b/, "superhero"],
    [/\b(spaceship|sci-?fi|robot)\b/, "sci-fi"],
    [/\b(fantasy|castle|elf|wizard)\b/, "fantasy-world"],
    [/\b(documentary|interview)\b/, "documentary"],
    [/\b(conversation|talking|dialogue)\b/, "dialogue-scene"],
  ];
  for (const [re, id] of rules) if (re.test(t)) return id;
  return "movie-scene";
}
