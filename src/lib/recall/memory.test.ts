import { describe, expect, it } from "vitest";
import { buildMemoryGraph, memoryNeighbors, searchMemory } from "./memory";
import type { RecallData } from "./types";

const DATA = {
  folders: [
    { id: "f_root", name: "Websites", parentId: null, autoGenerated: false, createdAt: "" },
    { id: "f_domains", name: "Domains", parentId: "f_root", autoGenerated: false, createdAt: "" },
    { id: "f_profile", name: "Bighomie AI", parentId: "f_root", autoGenerated: false, createdAt: "" },
  ],
  items: [
    {
      id: "i_domain",
      title: "bighomieai.com on Cloudflare",
      body: "Renews 2027-11-02",
      summary: "Domain and renewal",
      kind: "website",
      source: "manual",
      folderId: "f_domains",
      tags: ["domain", "cloudflare"],
      createdAt: "2026-01-01T00:00:00.000Z",
      updatedAt: "2026-02-01T00:00:00.000Z",
    },
  ],
  profiles: [
    {
      id: "p_big",
      kind: "business",
      displayName: "Bighomie AI",
      folderId: "f_profile",
      itemId: null,
      fields: [],
      accounts: [
        {
          id: "a_domain",
          label: "Domain — bighomieai.com",
          kind: "domain",
          url: "https://bighomieai.com",
          renewalDate: "2027-11-02",
          createdAt: "",
          updatedAt: "",
        },
      ],
      tags: ["domain"],
      createdAt: "",
      updatedAt: "",
    },
  ],
} as unknown as RecallData;

describe("memory graph", () => {
  it("draws every folder, item, profile and account", () => {
    const graph = buildMemoryGraph(DATA);
    expect(graph.stats.folders).toBe(3);
    expect(graph.stats.items).toBe(1);
    expect(graph.stats.profiles).toBe(1);
    expect(graph.stats.accounts).toBe(1);
    expect(graph.nodes.some((n) => n.id === "profile:p_big")).toBe(true);
    expect(graph.nodes.some((n) => n.id === "account:p_big:a_domain")).toBe(true);
    expect(graph.nodes.some((n) => n.id === "item:i_domain")).toBe(true);
  });

  it("connects folders to their children and profiles to their folder", () => {
    const graph = buildMemoryGraph(DATA);
    expect(graph.edges.some((e) => e.from === "folder:f_root" && e.to === "folder:f_domains")).toBe(true);
    expect(graph.edges.some((e) => e.from === "folder:f_profile" && e.to === "profile:p_big")).toBe(true);
    expect(graph.edges.some((e) => e.kind === "account")).toBe(true);
  });

  it("links an account to a record that mentions the same domain", () => {
    const graph = buildMemoryGraph(DATA);
    expect(
      graph.edges.some(
        (e) =>
          e.kind === "link" &&
          e.from === "account:p_big:a_domain" &&
          e.to === "item:i_domain",
      ),
    ).toBe(true);
  });

  it("searches titles, profiles and the text inside a record", () => {
    const graph = buildMemoryGraph(DATA);
    expect(searchMemory(graph, "bighomieai").some((n) => n.id === "item:i_domain" || n.id === "profile:p_big")).toBe(true);
    // "Renews 2027-11-02" only exists in the body, not the title or summary.
    expect(searchMemory(graph, "renews").some((n) => n.id === "item:i_domain")).toBe(true);
    const neighbors = memoryNeighbors(graph, "profile:p_big");
    expect(neighbors.some((n) => n.node.id === "folder:f_profile")).toBe(true);
  });
});
