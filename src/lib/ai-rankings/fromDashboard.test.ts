import { describe, expect, it } from "vitest";
import { inRankingsFolder, isRankingsName, matchTool } from "./fromDashboard";
import type { Folder } from "@/lib/recall/types";
import type { Tool } from "./types";

const folder = (id: string, name: string, parentId: string | null = null) =>
  ({ id, name, parentId, autoGenerated: false }) as Folder;

const tool = (name: string, url = "") => ({ id: name, name, url }) as Tool;

describe("the AI Rankings folder", () => {
  it("matches however the name was typed", () => {
    for (const n of ["AI Rankings", "ai ranking", "AI-Rankings", " ai rankings "]) {
      expect(isRankingsName(n)).toBe(true);
    }
    expect(isRankingsName("AI Rankings old")).toBe(false);
    expect(isRankingsName("Rankings")).toBe(false);
  });

  it("covers the folder and everything nested inside it, nothing else", () => {
    const folders = [folder("r", "AI Rankings"), folder("v", "Video", "r"), folder("k", "Kling", "v"), folder("x", "Recipes")];
    expect(inRankingsFolder(folders, "r")).toBe(true);
    expect(inRankingsFolder(folders, "k")).toBe(true);
    expect(inRankingsFolder(folders, "x")).toBe(false);
    expect(inRankingsFolder(folders, null)).toBe(false);
  });
});

describe("already on the board", () => {
  const board = [tool("Kling 3", "https://klingai.com/"), tool("comfyanonymous/ComfyUI")];

  it("matches a link regardless of scheme, www and trailing slash", () => {
    expect(matchTool("whatever", "http://www.klingai.com", board)?.name).toBe("Kling 3");
  });

  it("matches a name regardless of case and punctuation", () => {
    expect(matchTool("kling-3", "", board)?.name).toBe("Kling 3");
    expect(matchTool("ComfyAnonymous / ComfyUI", "", board)?.name).toBe("comfyanonymous/ComfyUI");
  });

  it("does not invent a match", () => {
    expect(matchTool("Kling 2", "", board)).toBeUndefined();
    expect(matchTool("", "", board)).toBeUndefined();
  });
});
