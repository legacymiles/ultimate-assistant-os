// ---------------------------------------------------------------------------
// Profiles ⇄ the Dashboard (Recall): Folders, Memory and Photos.
//
// The owner asked for ONE profiles app that is "synced with the memory and
// folder tab and photos tab". Those tabs all read the Dashboard's one blob
// (recall:v1: folders, items, profiles). So Profiles mirrors into it:
//
//   · every real profile gets a folder under a "Profiles" folder, nested the
//     same way the profiles are, renamed and moved when they are;
//   · inside it, one searchable note holding the profile's details (private
//     values left out), so Folders search, the Memory graph and the
//     Dashboard's own agent all find it;
//   · photos uploaded to a profile land in Photos › <profile>, so the Photos
//     tab shows them too.
//
// And reads back: a profile's gallery also shows every picture already in its
// folder or its Photos folder, wherever it was added.
//
// mirrorPlan() and recallMediaFor() are pure (tested); syncToRecall() is the
// one place that touches the Dashboard store.
// ---------------------------------------------------------------------------

import { newId } from "./changes";
import { ROOT } from "./seed";
import type { Media, ProfileNode, ProfilesData, RecallLink } from "./types";
import type { Folder, Item, RecallData } from "@/lib/recall/types";

export const PROFILES_FOLDER = "Profiles";
const PHOTOS_ROOT_NAME = "Photos";

const nowIso = () => new Date().toISOString();

/** The note text for a profile: every non-private row, by section. */
export function noteBody(node: ProfileNode): string {
  const parts: string[] = [];
  if (node.sub) parts.push(node.sub);
  for (const s of node.sections) {
    const rows = s.items.filter((i) => !i.secret && !i.noAi).map((i) => `- ${i.k}: ${i.v}${i.meta ? ` (${i.meta})` : ""}`);
    if (rows.length) parts.push(`${s.title}\n${rows.join("\n")}`);
  }
  return parts.join("\n\n");
}

export interface MirrorResult {
  recall: RecallData;
  /** Links to write back onto the profiles. */
  links: Record<string, RecallLink>;
  /** Uploaded media id → the Dashboard image item it became. */
  media: Record<string, string>;
  changed: boolean;
}

function isPhotosRoot(f: Folder): boolean {
  return f.parentId === null && (f.role === "photos" || f.name.toLowerCase() === PHOTOS_ROOT_NAME.toLowerCase());
}

/**
 * What the Dashboard should look like for these profiles. Pure: takes both
 * blobs, returns a new Dashboard blob plus the links to remember.
 */
export function mirrorPlan(profiles: ProfilesData, input: RecallData): MirrorResult {
  const recall: RecallData = { folders: input.folders.map((f) => ({ ...f })), items: input.items.map((i) => ({ ...i })), profiles: input.profiles };
  const links: Record<string, RecallLink> = {};
  const media: Record<string, string> = {};
  let changed = false;
  const folderById = new Map(recall.folders.map((f) => [f.id, f]));
  const itemById = new Map(recall.items.map((i) => [i.id, i]));

  const makeFolder = (name: string, parentId: string | null, extra: Partial<Folder> = {}): Folder => {
    const f: Folder = { id: newId("fld"), name, parentId, autoGenerated: false, createdAt: nowIso(), ...extra };
    recall.folders.push(f);
    folderById.set(f.id, f);
    changed = true;
    return f;
  };

  const real = (n?: ProfileNode) => Boolean(n && !n.example && !n.archived && !n.hidden && n.id !== ROOT);
  const anyReal = Object.values(profiles.nodes).some((n) => real(n));
  if (!anyReal) return { recall: input, links, media, changed: false };

  const root =
    recall.folders.find((f) => f.parentId === null && f.name === PROFILES_FOLDER) ??
    makeFolder(PROFILES_FOLDER, null, { description: "Mirrored from Profiles — edit them there.", icon: "users" });
  let photosRoot: Folder | null = recall.folders.find(isPhotosRoot) ?? null;

  const walk = (parentId: string, parentFolder: Folder) => {
    for (const childId of profiles.nodes[parentId]?.children ?? []) {
      const node = profiles.nodes[childId];
      if (!node || node.archived || node.hidden) continue;
      // An example gets no folder, but something real the owner put inside
      // one still does — it goes where the example would have been.
      if (node.example) {
        walk(node.id, parentFolder);
        continue;
      }
      if (!real(node)) continue;
      const link: RecallLink = { ...(node.recall ?? {}) };

      // --- the folder -----------------------------------------------------
      let folder = link.folderId ? folderById.get(link.folderId) : undefined;
      if (!folder) {
        folder = makeFolder(node.name, parentFolder.id, { description: node.sub || undefined });
      } else {
        if (folder.name !== node.name) {
          folder.name = node.name;
          changed = true;
        }
        if (folder.parentId !== parentFolder.id && !wouldCycle(recall.folders, folder.id, parentFolder.id)) {
          folder.parentId = parentFolder.id;
          changed = true;
        }
      }
      link.folderId = folder.id;

      // --- the searchable note ------------------------------------------------
      const body = noteBody(node);
      const existing = link.noteId ? itemById.get(link.noteId) : undefined;
      if (body) {
        if (!existing) {
          const ts = nowIso();
          const item: Item = {
            id: newId("itm"),
            title: node.name,
            body,
            summary: node.sub || `${node.label} profile`,
            kind: "note",
            source: "manual",
            folderId: folder.id,
            tags: ["profile"],
            fields: { profile: node.id },
            createdAt: ts,
            updatedAt: ts,
          };
          recall.items.push(item);
          itemById.set(item.id, item);
          link.noteId = item.id;
          changed = true;
        } else if (existing.body !== body || existing.title !== node.name || existing.folderId !== folder.id) {
          existing.body = body;
          existing.title = node.name;
          existing.folderId = folder.id;
          existing.summary = node.sub || existing.summary;
          existing.updatedAt = nowIso();
          changed = true;
        }
      }

      // --- photos uploaded here -----------------------------------------------
      const uploads = node.media.filter((m) => m.src && !m.recallItemId && !m.fromRecall);
      if (uploads.length) {
        if (!photosRoot) photosRoot = makeFolder(PHOTOS_ROOT_NAME, null, { role: "photos" });
        let pf = link.photosFolderId ? folderById.get(link.photosFolderId) : undefined;
        if (!pf) pf = recall.folders.find((f) => f.parentId === photosRoot!.id && f.name === node.name) ?? makeFolder(node.name, photosRoot.id);
        link.photosFolderId = pf.id;
        for (const m of uploads) {
          const ts = nowIso();
          const item: Item = {
            id: newId("itm"),
            title: m.caption,
            body: "",
            summary: `${m.kind === "video" ? "Video" : "Photo"} of ${node.name}`,
            kind: "image",
            source: "manual",
            folderId: pf.id,
            tags: ["profile"],
            attachment: { name: m.caption, type: "image/jpeg", size: Math.round((m.src!.length * 3) / 4), url: m.src, category: "image" },
            createdAt: ts,
            updatedAt: ts,
          };
          recall.items.push(item);
          itemById.set(item.id, item);
          media[m.id] = item.id;
          changed = true;
        }
      }

      if (JSON.stringify(link) !== JSON.stringify(node.recall ?? {})) links[node.id] = link;
      walk(node.id, folder);
    }
  };
  walk(ROOT, root);
  return { recall: changed ? recall : input, links, media, changed };
}

function wouldCycle(folders: Folder[], folderId: string, candidateParent: string | null): boolean {
  let cur = candidateParent;
  const seen = new Set<string>();
  while (cur && !seen.has(cur)) {
    if (cur === folderId) return true;
    seen.add(cur);
    cur = folders.find((f) => f.id === cur)?.parentId ?? null;
  }
  return false;
}

function subtree(folders: Folder[], rootId: string): Set<string> {
  const out = new Set<string>([rootId]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const f of folders) if (f.parentId && out.has(f.parentId) && !out.has(f.id)) {
      out.add(f.id);
      grew = true;
    }
  }
  return out;
}

/** Pictures already in the Dashboard for this profile (its folder or Photos folder). */
export function recallMediaFor(node: ProfileNode, recall: RecallData): Media[] {
  const roots = [node.recall?.folderId, node.recall?.photosFolderId].filter((x): x is string => Boolean(x));
  if (!roots.length) return [];
  const ids = new Set<string>();
  for (const r of roots) for (const id of subtree(recall.folders, r)) ids.add(id);
  const mine = new Set(node.media.map((m) => m.recallItemId).filter(Boolean));
  return recall.items
    .filter((i) => i.folderId && ids.has(i.folderId) && !mine.has(i.id) && (i.kind === "image" || i.attachment?.category === "video") && i.attachment?.url)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .map((i) => ({
      id: `rc-${i.id}`,
      kind: i.attachment?.category === "video" ? ("video" as const) : ("photo" as const),
      src: i.attachment!.url!,
      caption: i.title || "Photo",
      date: new Date(i.createdAt).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" }),
      fromRecall: true,
    }));
}

// --- the one place that touches the Dashboard store ---------------------------

/**
 * Mirror profiles into the Dashboard. Returns the links/media ids to save back
 * onto the profiles, or null when nothing changed. Never throws.
 */
export async function syncToRecall(profiles: ProfilesData): Promise<Pick<MirrorResult, "links" | "media"> | null> {
  try {
    const [{ getData, saveData, KEY }, { reconcile }, { scopedKey }] = await Promise.all([
      import("@/lib/recall/store"),
      import("@/lib/sync/appState"),
      import("@/lib/sync/identity"),
    ]);
    // Settle against the account first, and never write from a device that
    // holds no Dashboard copy: saving the empty seed there would be stamped
    // newest and replace the owner's real folders on every other device.
    await reconcile(KEY);
    if (window.localStorage.getItem(scopedKey(KEY)) == null) return null;
    const plan = mirrorPlan(profiles, getData());
    if (!plan.changed && !Object.keys(plan.links).length) return null;
    if (plan.changed) saveData(plan.recall);
    return { links: plan.links, media: plan.media };
  } catch {
    return null;
  }
}

/** Read the Dashboard blob without writing anything. */
export async function readRecall(): Promise<RecallData | null> {
  try {
    const { getData } = await import("@/lib/recall/store");
    return getData();
  } catch {
    return null;
  }
}
