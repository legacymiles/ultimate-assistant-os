import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { ProfilesBoard } from "./ProfilesBoard";
import { MemoryBoard } from "./MemoryBoard";
import { ProfileView } from "./ProfileView";
import { ProfileWizard } from "./ProfileWizard";
import { buildProfileFields } from "@/lib/recall/profiles";
import type { Profile, RecallData } from "@/lib/recall/types";

const PROFILE: Profile = {
  id: "p1",
  kind: "person",
  role: "child",
  displayName: "Mason",
  headline: "My son",
  folderId: "f1",
  itemId: "i1",
  fields: buildProfileFields("person", [{ label: "Birthday", value: "2012-03-14" }], "Mason"),
  accounts: [
    {
      id: "a1",
      label: "Trump account",
      provider: "Trump Media",
      kind: "brokerage",
      openedDate: "2024-06-01",
      value: "1250",
      currency: "USD",
      createdAt: "2026-01-01T00:00:00.000Z",
      updatedAt: "2026-01-01T00:00:00.000Z",
    },
  ],
  tags: ["profile", "child"],
  createdAt: "2026-01-01T00:00:00.000Z",
  updatedAt: "2026-01-01T00:00:00.000Z",
};

const DATA: RecallData = {
  folders: [
    { id: "f0", name: "Profiles", parentId: null, autoGenerated: false, createdAt: "" },
    { id: "f1", name: "Mason", parentId: "f0", autoGenerated: false, createdAt: "" },
  ],
  items: [
    {
      id: "i1",
      title: "Mason — Person profile",
      body: "Birthday: 2012-03-14",
      summary: "Person profile",
      kind: "note",
      source: "manual",
      folderId: "f1",
      tags: ["profile"],
      profileId: "p1",
      fields: {},
      createdAt: "",
      updatedAt: "",
    },
  ],
  profiles: [PROFILE],
};

const noop = () => {};

describe("profile surfaces render", () => {
  it("renders the profiles board without a DOM", () => {
    const html = renderToStaticMarkup(
      createElement(ProfilesBoard, {
        data: DATA,
        onOpenProfile: noop,
        onAddProfile: noop,
        onOpenMemory: noop,
        onOpenFolder: noop,
      }),
    );
    expect(html).toContain("Mason");
    expect(html).toContain("Add profile");
  });

  it("renders the profile detail with its account placeholders", () => {
    const html = renderToStaticMarkup(
      createElement(ProfileView, {
        profile: PROFILE,
        data: DATA,
        onBack: noop,
        onData: noop,
        onOpenFolder: noop,
        onOpenItem: noop,
        onOpenMemory: noop,
        onAsk: noop,
        onToast: noop,
      }),
    );
    expect(html).toContain("Trump account");
    expect(html).toContain("2012-03-14");
    expect(html).toContain("Open folder");
  });

  it("renders the memory web from the same records", () => {
    const html = renderToStaticMarkup(
      createElement(MemoryBoard, {
        data: DATA,
        onOpenFolder: noop,
        onOpenItem: noop,
        onOpenProfile: noop,
        onAsk: noop,
      }),
    );
    expect(html).toContain("Mason");
    expect(html).toContain("Everything, connected");
  });

  it("renders the add-profile conversation", () => {
    const html = renderToStaticMarkup(
      createElement(ProfileWizard, {
        open: true,
        data: DATA,
        onClose: noop,
        onCreated: noop,
      }),
    );
    expect(html).toContain("What do you know?");
    expect(html).toContain("Ask Jarvis");
  });
});
