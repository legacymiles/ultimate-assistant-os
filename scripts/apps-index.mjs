// ---------------------------------------------------------------------------
// Writes docs/apps/README.md — the list of every app, built from the catalog.
//
//   node scripts/apps-index.mjs           rewrite the list
//   node scripts/apps-index.mjs --check   exit 1 if it is out of date
//
// The catalog (src/lib/catalog.ts) is the single source of truth for which apps
// exist; src/lib/studio/plugins.ts says where each one shows. This turns the
// two into one table any AI tool can read without running TypeScript, with a
// link to each app's doc and screenshot, and flags the ones that lack either.
// It also copies the docs into src/lib/timeline/app-docs.json, which is how
// Projects Timeline shows each app's features, look and code map.
// ---------------------------------------------------------------------------

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const OUT = "docs/apps/README.md";
// The docs themselves, for Projects Timeline to show (src/lib/timeline/appDocs.ts).
const DOCS_JSON = "src/lib/timeline/app-docs.json";
// Windows checkouts have CRLF line endings; the parsing below expects LF.
const lf = (s) => s.replace(/\r\n/g, "\n");
const catalog = lf(readFileSync("src/lib/catalog.ts", "utf8"));
const plugins = lf(readFileSync("src/lib/studio/plugins.ts", "utf8"));

/** The PROJECTS array's objects, read out of the TypeScript without compiling it. */
function projects() {
  const body = catalog.slice(catalog.indexOf("export const PROJECTS"));
  const end = body.indexOf("\n];");
  const out = [];
  for (const chunk of body.slice(0, end).split(/\n  \{\n/).slice(1)) {
    const str = (key) => chunk.match(new RegExp(`(?:^|\\n)    ${key}:\\s*"((?:[^"\\\\]|\\\\.)*)"`))?.[1];
    const slug = str("slug");
    if (slug) {
      out.push({
        slug,
        title: str("title") ?? slug,
        tag: str("tag") ?? "",
        category: str("category") ?? "",
        status: str("status") ?? "",
        appUrl: str("appUrl") ?? "",
      });
    }
  }
  return out;
}

/** A `const NAME = [ "a", "b" ]` list from plugins.ts. */
function list(name) {
  const m = plugins.match(new RegExp(`export const ${name}[^=]*=\\s*\\[([\\s\\S]*?)\\]`));
  return new Set([...(m?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((x) => x[1]));
}

function mergedInto() {
  const m = plugins.match(/export const MERGED_INTO[^=]*=\s*\{([\s\S]*?)\};/);
  return Object.fromEntries([...(m?.[1] ?? "").matchAll(/"([^"]+)":\s*"([^"]+)"/g)].map((x) => [x[1], x[2]]));
}

const PLUGIN = list("PLUGIN_SLUGS");
const WIDGET = list("WIDGET_SLUGS");
const TOOLBOX = list("TOOLBOX_SLUGS");
const MERGED = mergedInto();

function showsAs(slug) {
  if (MERGED[slug]) return `inside ${MERGED[slug]}`;
  if (WIDGET.has(slug)) return "Dashboard widget";
  if (TOOLBOX.has(slug)) return "Jarvis Toolbox tab";
  if (PLUGIN.has(slug)) return "Jarvis › App plugins";
  return "hub grid";
}

const apps = projects();
const extra = ["hub", "dashboard", "skills-library"].filter((s) => !apps.some((a) => a.slug === s));
const missingDoc = [];
const missingLook = [];
const cell = (s) => s.replace(/\|/g, "\\|");

const rows = apps.map((a) => {
  const doc = existsSync(`docs/apps/${a.slug}.md`);
  const look = existsSync(`public/look/${a.slug}.jpg`);
  if (!doc) missingDoc.push(a.slug);
  if (!look) missingLook.push(a.slug);
  const name = doc ? `[${cell(a.title)}](${a.slug}.md)` : `${cell(a.title)} — **no doc**`;
  return `| ${name} | \`${a.slug}\` | ${a.status} | ${showsAs(a.slug)} | ${a.category} | ${cell(a.tag)} | ${look ? `[jpg](../../public/look/${a.slug}.jpg)` : "—"} |`;
});

const text = [
  "# Every app",
  "",
  "Generated by `node scripts/apps-index.mjs` from `src/lib/catalog.ts` and",
  "`src/lib/studio/plugins.ts`. Do not edit by hand: change the catalog, then re-run it.",
  "",
  "Open an app's doc before changing it. Its **Features** list is what must still work afterwards.",
  "",
  `**The website itself** (home page, carousel, sign-in, legal): [hub.md](hub.md).` +
    (extra.length ? ` Not in the catalog but documented: ${extra.filter((s) => s !== "hub" && existsSync(`docs/apps/${s}.md`)).map((s) => `[${s}](${s}.md)`).join(" · ")}.` : ""),
  "",
  `${apps.length} apps.` +
    (missingDoc.length ? ` **Missing a doc:** ${missingDoc.join(", ")}.` : " Every app has a doc.") +
    (missingLook.length ? ` Missing a screenshot: ${missingLook.join(", ")}.` : " Every app has a screenshot."),
  "",
  "| App | Slug | Status | Shows as | Category | What it is | Look |",
  "|---|---|---|---|---|---|---|",
  ...rows,
  "",
].join("\n");

const docs = Object.fromEntries(
  readdirSync("docs/apps")
    .filter((f) => f.endsWith(".md") && !f.startsWith("_") && f !== "README.md")
    .sort()
    .map((f) => [f.slice(0, -3), readFileSync(`docs/apps/${f}`, "utf8").replace(/\r\n/g, "\n")]),
);
const docsJson = JSON.stringify(docs, null, 1) + "\n";
const read = (p) => (existsSync(p) ? readFileSync(p, "utf8").replace(/\r\n/g, "\n") : "");

if (process.argv.includes("--check")) {
  if (read(OUT) !== text || read(DOCS_JSON) !== docsJson) {
    console.error(`${OUT} or ${DOCS_JSON} is out of date. Run: node scripts/apps-index.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is current (${apps.length} apps).`);
} else {
  writeFileSync(OUT, text);
  writeFileSync(DOCS_JSON, docsJson);
  console.log(`Wrote ${OUT}: ${apps.length} apps, ${missingDoc.length} without a doc, ${missingLook.length} without a screenshot.`);
}
